#!/usr/bin/env python3
"""Generate packaged LÖVE resource constants from the canonical JSON manifest.

The source of truth is data/catalog/. Never edit catalog_generated.lua by hand.
Use --check in CI: packaged Lua and JSON must match byte-for-byte.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "data" / "catalog"
OUTPUT = ROOT / "game" / "love" / "objects" / "catalog_generated.lua"


def render_lua(catalog=CATALOG):
    catalog = Path(catalog)
    manifest = json.loads((catalog / "manifest.json").read_text(encoding="utf-8"))
    entries = {}
    for relative in manifest["definitions"]:
        entry = json.loads((catalog / relative).read_text(encoding="utf-8"))
        ident = entry["id"]
        if ident in entries:
            raise ValueError("duplicate definition ID: " + ident)
        entries[ident] = entry

    resources = []
    for ident in sorted(entries):
        entry = entries[ident]
        world = entry["components"].get("core:world_resource")
        if world is None:
            continue
        harvest = entry["components"].get("core:harvestable")
        if entry["kind"] != "resource" or harvest is None:
            raise ValueError("world resource must be a harvestable resource: " + ident)
        if not isinstance(world["radius"], (int, float)) or isinstance(world["radius"], bool) or world["radius"] <= 0:
            raise ValueError("invalid radius: " + ident)
        if world["render_kind"] not in ("tree", "rock"):
            raise ValueError("unknown render kind: " + ident)
        if not world["biomes"] or len(set(world["biomes"])) != len(world["biomes"]):
            raise ValueError("invalid biomes: " + ident)
        for drop in harvest["drops"]:
            if drop["def_id"] not in entries:
                raise ValueError("unknown drop definition: " + drop["def_id"])
        resources.append((ident, world, harvest))
    if not resources:
        raise ValueError("no packaged world resources")

    q = lambda s: json.dumps(s, ensure_ascii=True)
    lines = [
        "-- Generated by scripts/generate_love_catalog.py from data/catalog/.",
        "-- Do not edit; CI checks this file against the canonical JSON manifest.",
        "return {",
    ]
    for ident, world, harvest in resources:
        biomes = ",".join("[" + q(b) + "]=true" for b in sorted(world["biomes"]))
        drops = ",".join("{def_id=" + q(d["def_id"]) + ",count=" + str(d["count"]) + "}" for d in harvest["drops"])
        lines.extend([
            "  [" + q(ident) + "] = {",
            "    id=" + q(ident) + ",",
            "    kind=" + q(world["render_kind"]) + ",",
            "    biomes={" + biomes + "},",
            "    radius=" + str(world["radius"]) + ",",
            "    duration_ticks=" + str(harvest["duration_ticks"]) + ",",
            "    drops={" + drops + "},",
            "  },",
        ])
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if bundled registry differs from JSON")
    args = parser.parse_args()
    generated = render_lua()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != generated:
            parser.error("stale LÖVE catalog; regenerate via python scripts/generate_love_catalog.py")
        print("LOVE_CATALOG_SYNC_OK")
    else:
        OUTPUT.write_text(generated, encoding="utf-8")
        print("Generated", OUTPUT)


if __name__ == "__main__":
    main()
