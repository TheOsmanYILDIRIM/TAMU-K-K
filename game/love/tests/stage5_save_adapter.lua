package.path="./?.lua;./?/init.lua;"..package.path
local Json=require("save.json")
local Validate=require("save.validate")
local Adapter=require("save.stage5_adapter")
local Inventory=require("systems.inventory")
local Fixture=require("tests.save_v2_fixture")
local inv=Inventory.new(12)
local x=Adapter.inventory_snapshot(inv)
assert(getmetatable(x.slots).__json_array)
local state=Fixture.empty()
state.player.inventory=x
assert(Validate.check(state,{catalog=Fixture.catalog,generator_version=1,catalog_version=1}))
assert(Json.encode(state):find('"slots":%[%]'))
assert(inv:credit_harvest({type="HarvestCompleted",transaction_id="tx-negative",item_id="core:wood_log",amount=3}))
state.player.inventory=Adapter.inventory_snapshot(inv)
assert(state.player.inventory.slots[1].slot==1)
assert(state.player.inventory.slots[1].count==3)
assert(Validate.check(state,{catalog=Fixture.catalog,generator_version=1,catalog_version=1}))
local replay=Json.decode(Json.encode(state))
assert(getmetatable(replay.player.inventory.slots).__json_array)
assert(replay.player.inventory.slots[1].count==3)
local started=Adapter.terminal_commands({["craft:1"]={status="started"}},1)
assert(next(started)==nil)
local terminal=Adapter.terminal_commands({["craft:1"]={status="crafted"},
  ["place:1"]={status="placed"}},1)
assert(terminal["craft:1"].status=="crafted")
assert(terminal["place:1"].status=="placed")
local ok=pcall(Adapter.terminal_commands,{["x"]={status="in-progress"}},1)
assert(not ok)
print("STAGE5_SAVE_ADAPTER_PASS")
