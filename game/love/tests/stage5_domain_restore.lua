package.path="./?.lua;./?/init.lua;"..package.path
local Query=require("world.world_query")
local Water=require("world.collision_adapter")
local World=require("objects.world")
local Solid=require("objects.query")
local Inventory=require("systems.inventory")
local Craft=require("systems.crafting")
local Building=require("systems.building")
local Harvest=require("objects.harvesting")
local Restore=require("save.stage5_domain_restore")
local Clone=require("save.stage5_domain_clone")
local F=require("tests.save_v2_fixture")
local Catalog=require("systems.catalog")
local Json=require("save.json")
local query=Query.new(20261015)
local water=Water.new(query,8)
local world=World.new(query,water)
local solid=Solid.new(water,world)
local inv=Inventory.new(12)
local b=Building.new(inv,query,solid,F.world_id)
local live={query=query,solid=solid,world=world,inventory=inv,
  building=b,crafting=Craft.new(inv),harvesting=Harvest.new(world,38,inv)}
local state=F.next(F.empty())
local domain,pos=Restore.restore(live,state)
assert(live.inventory:count("core:wood_log")==0)
assert(domain.inventory:count("core:wood_log")==2)
assert(domain.inventory:count("core:workbench")==1)
assert(domain.world:is_depleted("worldobj:v1:20261015:-3:4"))
assert(domain.building.placed[F.placed_id])
assert(domain.building.placed[F.placed_id].box.w==32)
assert(pos.x==-123.5 and pos.y==55.75)
assert(not next(live.world.delta) and not next(live.building.placed))
Clone.publish(live,domain)
assert(live.inventory:count("core:wood_log")==2)
assert(live.building.placed[F.placed_id])
local corrupt=Json.decode(Json.encode(state))
corrupt.player.inventory.slots[1].def_id="invalid:missing"
assert(not pcall(Restore.restore,live,corrupt))
assert(live.inventory:count("core:wood_log")==2)
print("STAGE5_DOMAIN_RESTORE_OK detached reload and corrupt fail-closed")
